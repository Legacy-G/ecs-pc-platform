#!/usr/bin/env bash
# Enforce repository prose standards across all git-tracked text files.
# Fails on banned marketing words, AI self-references, em/en dashes in prose,
# emojis, and leftover placeholder markers.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

if command -v python >/dev/null 2>&1 && python -c "import sys" >/dev/null 2>&1; then
  PYTHON_BIN="python"
elif command -v python3 >/dev/null 2>&1 && python3 -c "import sys" >/dev/null 2>&1; then
  PYTHON_BIN="python3"
else
  echo "check-prose: python3 interpreter not found" >&2
  exit 1
fi

"$PYTHON_BIN" - <<'PY'
import re
import subprocess
import sys

EXCLUDED_PATHS = {
    "scripts/check-prose.sh",
}

BINARY_EXTENSIONS = (
    ".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".docx", ".zip", ".whl"
)

BANNED_PATTERNS = [
    r"\bcomprehensive\b",
    r"\brobust\b",
    r"\bseamless(?:ly)?\b",
    r"\bleverag(?:e|ed|es|ing)\b",
    r"\butiliz(?:e|ed|es|ing)\b",
    r"\bcutting-edge\b",
    r"\bstate-of-the-art\b",
    r"\bbest-in-class\b",
    r"\bdelv(?:e|ed|es|ing)\b",
    r"\bstreamlin(?:e|ed|es|ing)\b",
    r"\bempower(?:s|ed|ing)?\b",
    r"\bholistic\b",
    r"it is worth noting",
    r"in today's",
    r"generated by",
    r"as an ai",
    r"co-authored-by:.*(?:claude|copilot|gemini|gpt|openai|anthropic|cursor)",
    r"\blorem ipsum\b",
    r"\bexample123\b",
]

PLACEHOLDER_PATTERNS = [
    r"\bTODO\b",
    r"\bFIXME\b",
]

EMOJI_RE = re.compile(
    "["
    "\U0001F300-\U0001FAFF"
    "\U00002600-\U000027BF"
    "\U0001F900-\U0001F9FF"
    "\U0001FA70-\U0001FAFF"
    "]"
)

DASH_RE = re.compile(r"[\u2013\u2014]")

BANNED_RE = re.compile("|".join(BANNED_PATTERNS), re.IGNORECASE)
PLACEHOLDER_RE = re.compile("|".join(PLACEHOLDER_PATTERNS))

files_out = subprocess.check_output(["git", "ls-files"], text=True)
files = [f.strip() for f in files_out.splitlines() if f.strip()]

failures = []

for path in files:
    norm_path = path.replace("\\", "/")
    if norm_path in EXCLUDED_PATHS:
        continue
    if norm_path.lower().endswith(BINARY_EXTENSIONS):
        continue

    try:
        with open(path, "r", encoding="utf-8") as fh:
            lines = fh.readlines()
    except (UnicodeDecodeError, OSError):
        continue

    in_fence = False
    is_markdown = norm_path.endswith(".md")

    for lineno, raw_line in enumerate(lines, start=1):
        line = raw_line.rstrip("\r\n")
        if is_markdown and line.lstrip().startswith("```"):
            in_fence = not in_fence
            continue

        m_banned = BANNED_RE.search(line)
        if m_banned:
            failures.append(f"{norm_path}:{lineno}: banned phrase '{m_banned.group(0)}'")

        m_placeholder = PLACEHOLDER_RE.search(line)
        if m_placeholder:
            failures.append(f"{norm_path}:{lineno}: placeholder marker '{m_placeholder.group(0)}'")

        m_emoji = EMOJI_RE.search(line)
        if m_emoji:
            failures.append(f"{norm_path}:{lineno}: emoji character '{m_emoji.group(0)}'")

        if is_markdown and not in_fence:
            stripped = re.sub(r"`[^`]*`", "", line)
            m_dash = DASH_RE.search(stripped)
            if m_dash:
                failures.append(f"{norm_path}:{lineno}: em/en dash in prose '{m_dash.group(0)}'")

if failures:
    for item in failures:
        print(f"PROSE_CHECK_FAIL: {item}", file=sys.stderr)
    sys.exit(1)

print(f"check-prose: {len(files)} tracked files passed.")
PY
